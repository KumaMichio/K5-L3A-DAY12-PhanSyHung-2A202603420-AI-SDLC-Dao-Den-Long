#!/usr/bin/env node
// Regenerates docs/proof/<phase>/ from the real CLI (never hand-edit the outputs).
// Usage: npm run proof            (after npm run build)
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { posix } from 'node:path';

const { join } = posix; // same text on Windows and Linux, so CI can diff the committed proof

const phase = process.argv[2] ?? 'phase-1';
const scen = join('scenarios', phase);
const outDir = join('docs', 'proof', phase);
mkdirSync(outDir, { recursive: true });
const contract = JSON.parse(readFileSync('game.contract.json', 'utf8'));
const [cmd, ...pre] = contract.headless_cmd.split(' ');

const cases = [
  { name: 'default-seed1', args: ['--seed', '1', '--ticks', '3600'], proves: 'Default Night 1 world (random motes/shades, seeded); standing still -> shades catch Mây' },
  { name: 'win', scenario: 'win', inputs: 'win', args: ['--seed', '1', '--ticks', '600'], proves: 'Walk, pick 5 motes, deposit, light last lantern -> won/all_lit + bonus' },
  { name: 'hit-lose', scenario: 'hit-lose', args: ['--seed', '1', '--ticks', '600'], proves: 'Shade chase + hit, drop ratio, invulnerability, lost/no_flames' },
  { name: 'pulse', scenario: 'pulse', inputs: 'pulse', args: ['--seed', '1', '--ticks', '240'], proves: 'Pulse stuns only shades within pulse_radius, costs light, scores per_stun' },
  { name: 'safe-zone', scenario: 'safe-zone', args: ['--seed', '1', '--ticks', '900', '--snapshot-every', '60'], proves: 'Shade cannot enter safe_radius around a lantern; no hit' },
  { name: 'dawn', scenario: 'dawn', args: ['--seed', '1', '--ticks', '1000', '--snapshot-every', '30'], proves: 'Time runs out -> lost/dawn at tick 120' },
];

const sha = (p) => createHash('sha256').update(readFileSync(p)).digest('hex').slice(0, 16);
const run = (args) => spawnSync(cmd, [...pre, '--night', '1', ...args], { encoding: 'utf8' });

let md = `# Proof — ${phase}\n\nGenerated by \`npm run proof\` from the real headless CLI (\`${contract.headless_cmd}\`). Do not edit by hand.\n\n`;
md += '| Case | Proves | Exit | End line | Key events | Determinism (2 runs) |\n|---|---|---|---|---|---|\n';
let ok = true;
for (const c of cases) {
  const args = [...c.args];
  if (c.scenario) args.push('--scenario', join(scen, `${c.scenario}.scenario.json`));
  if (c.inputs) args.push('--inputs', join(scen, `${c.inputs}.inputs.json`));
  const out = join(outDir, `${c.name}.jsonl`);
  const again = join(outDir, `${c.name}.rerun.tmp`);
  const r1 = run([...args, '--out', out]);
  const r2 = run([...args, '--out', again]);
  const same = existsSync(again) && sha(out) === sha(again);
  const lines = readFileSync(out, 'utf8').trim().split('\n').map((l) => JSON.parse(l));
  const events = lines.filter((l) => l.type === 'event').map((e) => `${e.tick}:${e.name}`);
  const shown = events.length > 8 ? [...events.slice(0, 6), '…', ...events.slice(-2)] : events;
  ok &&= r1.status === 0 && r2.status === 0 && same;
  md += `| \`${c.name}\` | ${c.proves} | ${r1.status} | \`${JSON.stringify(lines.at(-1))}\` | ${shown.join(', ') || '—'} | ${same ? `identical (${sha(out)})` : 'DIFFERENT'} |\n`;
  spawnSync(process.execPath, ['-e', `require('fs').rmSync(${JSON.stringify(again)}, { force: true })`]);
}

const bad = run(['--seed', '1', '--ticks', '10', '--inputs', join(scen, 'bad.inputs.json'), '--out', join(outDir, 'bad.tmp')]);
ok &&= bad.status === 2;
md += `\nMalformed inputs (\`bad.inputs.json\`, duplicate tick): exit **${bad.status}**, stderr: \`${bad.stderr.trim()}\`\n`;
md += `\nCommand lines: see \`scripts/proof.mjs\`. Inputs/scenarios: \`${scen}/\`. Overall: **${ok ? 'PASS' : 'FAIL'}**\n`;
writeFileSync(join(outDir, 'README.md'), md);
console.log(md);
process.exit(ok ? 0 : 1);
