#!/usr/bin/env node
// Regenerates docs/proof/<phase>/ from the real CLI (never hand-edit the outputs).
// Cases come from scenarios/<phase>/cases.json. Usage: node scripts/proof.mjs phase-2
// Each case runs twice; the sha256 of both outputs must match (determinism).
// Earlier phases' proof is frozen at their tag: regenerate it only from a checkout of that tag.
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { posix } from 'node:path';

const { join } = posix; // same text on Windows and Linux, so CI can diff the committed proof

const phase = process.argv[2] ?? 'phase-2';
const scen = join('scenarios', phase);
const outDir = join('docs', 'proof', phase);
mkdirSync(outDir, { recursive: true });
const contract = JSON.parse(readFileSync('game.contract.json', 'utf8'));
const [cmd, ...pre] = contract.headless_cmd.split(' ');
const { cases, bad } = JSON.parse(readFileSync(join(scen, 'cases.json'), 'utf8'));

const sha = (p) => createHash('sha256').update(readFileSync(p)).digest('hex').slice(0, 16);
const run = (args) => spawnSync(cmd, [...pre, ...args], { encoding: 'utf8' });
const fileArgs = (c) => [
  ...(c.scenario ? ['--scenario', join(scen, `${c.scenario}.scenario.json`)] : []),
  ...(c.inputs ? ['--inputs', join(scen, `${c.inputs}.inputs.json`)] : []),
];

let md = `# Proof — ${phase}\n\nGenerated by \`node scripts/proof.mjs ${phase}\` from the real headless CLI (\`${contract.headless_cmd}\`, contract ${contract.contract_version}). Do not edit by hand.\n\n`;
md += '| Case | Night | Proves | Exit | End line | Key events | Determinism (2 runs) |\n|---|---|---|---|---|---|---|\n';
let ok = true;
for (const c of cases) {
  const args = ['--seed', String(c.seed ?? 1), '--night', String(c.night ?? 1), '--ticks', String(c.ticks), ...(c.every ? ['--snapshot-every', String(c.every)] : []), ...fileArgs(c)];
  const out = join(outDir, `${c.name}.jsonl`);
  const again = join(outDir, `${c.name}.rerun.tmp`);
  const r1 = run([...args, '--out', out]);
  const r2 = run([...args, '--out', again]);
  const same = existsSync(again) && sha(out) === sha(again);
  rmSync(again, { force: true });
  const lines = readFileSync(out, 'utf8').trim().split('\n').map((l) => JSON.parse(l));
  const events = lines.filter((l) => l.type === 'event' && l.name !== 'night_start').map((e) => `${e.tick}:${e.name}`);
  const shown = events.length > 8 ? [...events.slice(0, 6), `… (${events.length} total)`, ...events.slice(-2)] : events;
  ok &&= r1.status === 0 && r2.status === 0 && same;
  md += `| \`${c.name}\` | ${c.night ?? 1} | ${c.proves} | ${r1.status} | \`${JSON.stringify(lines.at(-1))}\` | ${shown.join(', ') || '—'} | ${same ? `identical (${sha(out)})` : 'DIFFERENT'} |\n`;
}

if (bad) {
  const r = run(['--seed', '1', '--night', String(bad.night), '--ticks', '10', ...fileArgs(bad), '--out', join(outDir, 'bad.tmp')]);
  rmSync(join(outDir, 'bad.tmp'), { force: true });
  ok &&= r.status === bad.expectExit;
  md += `\nMalformed file (\`${bad.scenario ?? bad.inputs}\`): exit **${r.status}** (expected ${bad.expectExit}), stderr: \`${r.stderr.trim()}\`\n`;
}
md += `\nInputs/scenarios: \`${scen}/\` (case list: \`cases.json\`). Overall: **${ok ? 'PASS' : 'FAIL'}**\n`;
writeFileSync(join(outDir, 'README.md'), md);
console.log(md);
process.exit(ok ? 0 : 1);
